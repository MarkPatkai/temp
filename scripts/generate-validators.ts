import Ajv from 'ajv';
import standalone from 'ajv/dist/standalone/index.js';
import { mkdir, writeFile } from 'node:fs/promises';
import { SchemaCatalog } from '../packages/contracts/schema';

const ajv = new Ajv({ allErrors: true, strict: true, ownProperties: true, code: { source: true, esm: true } });
for (const [name, schema] of Object.entries(SchemaCatalog)) ajv.addSchema(schema, name);
let code = standalone(ajv, Object.fromEntries(Object.keys(SchemaCatalog).map(name => [name, name])));
const imports = new Map<string, string>();
code = code.replace(/require\("(ajv\/dist\/runtime\/[^"\n]+)"\)\.default/g, (_match, specifier: string) => {
  if (!imports.has(specifier)) imports.set(specifier, `runtime${imports.size}`); return imports.get(specifier)!;
});
if (/\brequire\(/.test(code)) throw new Error('Unsupported generated validator dependency');
const header = [...imports].map(([specifier, name]) => {
  if (specifier !== 'ajv/dist/runtime/ucs2length') throw new Error(`Add a portable helper for ${specifier}`);
  // Equivalent Unicode code-point length, with no CommonJS interop or runtime compiler.
  return `function ${name}(text) { let length = 0; for (const codePoint of text) length++; return length; }`;
}).join('\n');
await mkdir(new URL('../packages/contracts/generated/', import.meta.url), { recursive: true });
await writeFile(new URL('../packages/contracts/generated/validators.js', import.meta.url), `// Generated by npm run schemas:generate. Do not edit. No runtime eval.\n${header}\n${code}\n`);
await writeFile(new URL('../packages/contracts/generated/validators.d.ts', import.meta.url), Object.keys(SchemaCatalog).map(name => `export const ${name}: import('ajv').ValidateFunction;`).join('\n') + '\n');
await mkdir(new URL('../docs/schemas/', import.meta.url), { recursive: true });
for (const [name, schema] of Object.entries(SchemaCatalog)) await writeFile(new URL(`../docs/schemas/${name}.json`, import.meta.url), JSON.stringify(schema, null, 2) + '\n');
console.log('Generated standalone JSON Schema validators and schema artifacts.');
